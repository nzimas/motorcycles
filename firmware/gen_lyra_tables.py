#!/usr/bin/env python3
"""Writes firmware/lyra_tables.h: compact base tables plus inline lookups
(the full 129/128/128-entry tables cost 1.5 KB of image, which the unit
cannot afford: the image must end at or before RC17's 0x401CEFCC)."""
import pathlib
L=["/* Generated by firmware/gen_lyra_tables.py: do not edit. */","#include <stdint.h>"]
# Note increments at 48 kHz, 2^32 scale, 440 Hz at 69: the top octave (notes
# 120..131) stored, lower notes by right shift (error below 2^-20).
top=[round(440*2**((n-69)/12)/48000*2**32) for n in range(120,132)]
L.append("static const uint32_t lyra_note_top[12]={"+",".join(f"{x}u" for x in top)+"};")
L.append("static inline uint32_t lyra_note_inc_at(unsigned n){n=n>128?128:n;return lyra_note_top[n%12]>>(10u-n/12);}")
# Sharpness gain 2^(x/21) in Q12: one 21-entry period, octaves by shift.
g=[round(4096*2**(k/21)) for k in range(21)]
L.append("static const uint16_t lyra_sharp_base[21]={"+",".join(str(x) for x in g)+"};")
L.append("static inline uint32_t lyra_sharp_gain_at(unsigned x){x=x>127?127:x;return (uint32_t)lyra_sharp_base[x%21]<<(x/21);}")
# Hyper LFO increment per 32-sample block: 0.05 Hz at 1, doubling every 13 steps
# (0.05 Hz .. ~41 Hz at 127); 0 = off.
base=[round(0.05*2**(k/13)*32/48000*2**32) for k in range(13)]
L.append("static const uint32_t lyra_lfo_base[13]={"+",".join(f"{x}u" for x in base)+"};")
L.append("static inline uint32_t lyra_lfo_inc_at(unsigned h){if(!h)return 0;h=(h>127?127:h)-1;return lyra_lfo_base[h%13]<<(h/13);}")
(pathlib.Path(__file__).resolve().parent/'lyra_tables.h').write_text("\n".join(L)+"\n")
