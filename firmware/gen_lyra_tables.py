#!/usr/bin/env python3
"""Writes firmware/lyra_tables.h (note increments, sharpness gains, hyper-LFO rates)."""
import math,pathlib
L=["/* Generated by firmware/gen_lyra_tables.py: do not edit. */","#include <stdint.h>"]
inc=[min(0xffffffff,round(440*2**((n-69)/12)/48000*2**32)) for n in range(129)]
L.append("static const uint32_t lyra_note_inc[129]={"+",".join(f"{x}u" for x in inc)+"};")
g=[round(4096*2**(x/21)) for x in range(128)]
L.append("static const uint32_t lyra_sharp_gain[128]={"+",".join(str(x) for x in g)+"};")
lfo=[0]+[round(0.05*(800**((x-1)/126))*32/48000*2**32) for x in range(1,128)]
L.append("static const uint32_t lyra_lfo_inc[128]={"+",".join(f"{x}u" for x in lfo)+"};")
(pathlib.Path(__file__).resolve().parent/'lyra_tables.h').write_text("\n".join(L)+"\n")
